"""10-question practice set for comprehensions and functional patterns."""

# Q1 — List comprehension
# Build a list containing the squares of numbers from 1 through 10.

# Q2 — Conditional comprehension
# From a list of integers, create a list containing only even values.

# Q3 — Set comprehension
# Given a list of words, create a set containing their lengths.

# Q4 — Dictionary comprehension
# Create a dictionary mapping numbers 1 through 5 to their cubes.

# Q5 — Nested comprehension
# Flatten [[1, 2], [3, 4], [5, 6]] into [1, 2, 3, 4, 5, 6].

# Q6 — Generator expression
# Create a generator that produces the squares of 1 through 100.
# Explain why it can use less memory than a list comprehension.

# Q7 — map() and filter()
# Use map() to double numbers and filter() to keep only values above 10.

# Q8 — reduce()
# Use functools.reduce() to calculate the product of a sequence.
# Compare its readability with a normal loop.

# Q9 — sorted() and key=
# Sort [('A', 72), ('B', 91), ('C', 65)] by marks from highest to lowest.

# Q10 — Readability
# Rewrite an unnecessarily complicated nested comprehension as ordinary loops.
# Explain why the loop version is easier to maintain.
