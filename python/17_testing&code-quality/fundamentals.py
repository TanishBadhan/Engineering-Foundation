"""10-question practice set for Testing & Code Quality."""

# Q1 — assert
# Write assertions for a function that calculates a square. Include a boundary
# or invalid-case thought experiment.

# Q2 — Unit test
# Write two tests for add(a, b): one normal case and one negative-value case.

# Q3 — unittest
# Create a unittest.TestCase with at least two test methods for a small function.

# Q4 — pytest
# Rewrite the same behavior as plain pytest-style test functions using assert.

# Q5 — Test organization
# Design a tests/ directory for a small project containing users.py and math.py.

# Q6 — Edge cases
# For a function that averages a list, identify at least five meaningful test
# cases, including an empty-list behavior.

# Q7 — Defensive programming
# Decide which input validation belongs at an API/user boundary and which
# assumptions should remain internal. Explain your choices.

# Q8 — Debugging
# Given a failing test, write the sequence of steps you would follow to isolate
# the defect rather than immediately changing the code.

# Q9 — Logging
# Replace a production-style print statement with an appropriate logging call.
# Choose a useful level and explain why.

# Q10 — Code quality review
# Review a short function for naming, organization, PEP 8, documentation, and
# unnecessary complexity. Rewrite it to improve readability without changing behavior.
