"""10-question practice set for Type System & Modern Python."""

# Q1 — Annotations
# Annotate a function that receives a string and an integer and returns a string.

# Q2 — Built-in generics
# Annotate a list of integers and a dictionary mapping strings to floats.

# Q3 — Optional
# Annotate a function that may return a string or None. Explain what Optional
# means in this context.

# Q4 — Union
# Annotate a value that may be int or str using modern union syntax.

# Q5 — Any
# Give one justified use of Any and one situation where using Any would hide a
# useful type error.

# Q6 — Type alias
# Create a meaningful alias for a sensor reading or user ID and use it in a
# function annotation.

# Q7 — Callable
# Annotate a function that accepts another function taking two integers and
# returning an integer.

# Q8 — Generics
# Write a generic first(items) function that returns the first item while
# preserving the element type for a static type checker.

# Q9 — Static checking
# Explain the difference between a type checker finding a problem before runtime
# and runtime validation rejecting an invalid external input.

# Q10 — Structural typing
# Define a Protocol for a start() method and explain why a class can satisfy that
# protocol without inheriting from it.
