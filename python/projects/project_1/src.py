def add(a, b):
    return a + b


def multi(a, b):
    return a * b


def subt(a, b):
    return a - b


def div(a, b):
    if b == 0:
        return "Zero Division Error"
    return a/b


def mod(a, b):
    if b == 0:
        return "Zero Divison Error"
    return a % b


def sq(a):
    return a**2


def cube(a):
    return a**3
