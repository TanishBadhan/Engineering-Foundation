# Python Variables - Examples

# 1. Basic variable assignment
name = "Tanish"
age = 19
salary = 25000

print(name)
print(age)
print(salary)


# 2. Different data types
student_name = "Tanish"
student_age = 19
percentage = 67.0
is_student = True

print(student_name)
print(student_age)
print(percentage)
print(is_student)


# 3. Checking variable types
x = 100

print(type(x))


# 4. Reassigning a variable
score = 50
print(score)

score = 75
print(score)


# 5. Multiple assignment
x, y, z = 10, 20, 30

print(x)
print(y)
print(z)


# 6. Assigning the same value to multiple variables
a = b = c = 100

print(a)
print(b)
print(c)


# 7. Case-sensitive variable names
age = 19
Age = 20

print(age)
print(Age)